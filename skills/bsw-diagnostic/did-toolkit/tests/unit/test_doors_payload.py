SAMPLE_FSCS = """\
# ==============================================================================
# Generated from outputs/fscs/fscs.json -- do not edit this file by hand.
# ==============================================================================

Identifier $5001h - Vehicle mode

Description
This identifier returns the Vehicle mode

Data Type:\tIdentity

================================================================================

Identifier $0301h - End Of Line Test Status

Description
This identifier returns the End Of Line Test Status

================================================================================
"""


def test_fscs_split_parses_two_blocks_with_banner_stripped():
    blocks = fscs_split.split_text(SAMPLE_FSCS)
    assert [b.did_hex for b in blocks] == ["0x5001", "0x0301"]
    assert blocks[0].did_name == "Vehicle mode"
    assert blocks[0].heading == "Identifier $5001h - Vehicle mode"
    assert blocks[0].body.startswith("Description")
    assert "Data Type:" in blocks[0].body
    assert blocks[1].did_name == "End Of Line Test Status"


def test_fscs_split_pads_short_hex_and_uppercases():
    txt = "Identifier $f1h - Tiny\n\nbody only\n"
    blocks = fscs_split.split_text(txt)
    assert len(blocks) == 1
    assert blocks[0].did_hex == "0x00F1"


def test_fscs_split_skips_blank_separator_chunks():
    txt = SAMPLE_FSCS + "\n=================\n\n\n"  # trailing separator + blanks
    blocks = fscs_split.split_text(txt)
    assert [b.did_hex for b in blocks] == ["0x5001", "0x0301"]


