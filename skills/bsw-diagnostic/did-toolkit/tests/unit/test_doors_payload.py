"""Unit tests for the v2 (per-DID two-row) DOORS payload pipeline.

Covers:

* :mod:`scripts.fscs.doors.fscs_split` -- parse a renderer-produced
  FSCS_22.txt / FSCS_2E.txt string into per-DID heading/body blocks
  with the banner stripped.
* :mod:`scripts.fscs.doors.anchor` -- locate per-service anchor rows
  by exact and whitespace-normalised text match plus ``by_absolute_number``
  override.
* :mod:`scripts.fscs.doors.build_doors_payload` -- build the two
  per-service workbooks from a synthetic FSCS pair, validate the
  per-DID two-row layout (FS row carries Object Heading; CS row carries
  Object Text), and confirm the ``Common`` RB_Product semantics fan
  the cell out to every value-mapped product.
* :mod:`scripts.fscs.doors.doors_links` -- pair FS rows with the row
  that follows them (CS) by Object Heading match, and render a link
  xlsx whose source/target columns route CS -> FS by default.
"""

