def _write_minimal_yaml(path: Path, *, rb_product_overrides: dict | None = None,
                        product_token: str | None = None) -> None:
    """v1.16.0 minimal YAML: 17-col template-aligned defaults, FS/CS
    role-aware values, basename-only realizing templates."""
    overrides = ""
    if rb_product_overrides:
        overrides = "rb_product_overrides:\n"
        for k, v in rb_product_overrides.items():
            overrides += f"  '{k}': '{v}'\n"
    path.write_text(
        f"""
doors:
  document_uuid: "demo-module"
anchors:
  service_22:
    heading_field: "DescriptionOfRequirementRB"
    text: |-
      ${product_token or '22 anchor text'}
  service_2e:
    heading_field: "DescriptionOfRequirementRB"
    text: |-
      $2E anchor text
template:
  sheet: "CS Data"
  size_row: 1
  header_row: 2
  data_start: 3
defaults:
  isPicture: "no"
role_values:
  FS:
    RB_Referenced_Testcase: "SwT"
    RB_TestEnvironment: "Labcar/HIL"
  CS:
    RB_Referenced_Testcase: "CT"
    RB_TestEnvironment: "SIL Simulation"
value_maps:
  RB_Product:
    DPB: "DPB"
    ESP: "ESP 10"
{overrides}
realizing_paths:
  fs_template: "Dcm_CusDiag_Services_EcucValues_{{product_type}}.arxml"
  cs_template: "RBAPLCUST_{{did_hex_bare}}_{{did_name}}.c"
  customer_default: "rbcn"
columns:
  "Destination Object":  "row.destination"
  "Absolute Number":     "row.absolute_no"
  "Object Heading":      "row.heading"
  "Object Text":         "row.object_text"
  "RB_Realizing_SWitem": "row.realizing"
  "RB_Product":          "row.rb_product"
  "isPicture":           "literal:no"
upload:
  init_timeout: 1
  upload_timeout: 1
""".lstrip(),
        encoding="utf-8",
    )


def _write_project(path: Path) -> None:
    """v1.16.0: project.json no longer carries product_type. Operator
    workflows pin it via the Phase 1/2/3 ``--product-type`` CLI flag
    or the per-DID ``Product_Type`` CSV column."""
    path.write_text(
        json.dumps({"project": {"name": "Demo"}}),
        encoding="utf-8",
    )


def _write_fscs_json(path: Path, *, did_product_types: dict[str, str]) -> None:
    """Write a tiny fscs.json for the DOORS payload to consume.

    v1.16.0: ``RB_Product`` is sourced PER DID from
    ``fscs.json::dids[].product_type`` rather than from
    ``project.product_type``. Tests build a tiny JSON that maps
    ``did_hex (with 0x prefix)`` to its product_type token.
    """
    payload = {
        "schema_version": "1.5",
        "dids": [
            # The DOORS payload reader only cares about did_hex +
            # product_type, so keep the rest of the entry minimal.
            {"did_hex": did_hex.removeprefix("0x").upper(),
             "product_type": product_type}
            for did_hex, product_type in did_product_types.items()
        ],
    }
    path.write_text(json.dumps(payload), encoding="utf-8")


def _read_workbook(path: Path):
    openpyxl = pytest.importorskip("openpyxl")
    wb = openpyxl.load_workbook(path)
    ws = wb.active
    rows = []
    headers = [c.value for c in ws[2]]
    for r in ws.iter_rows(min_row=3, values_only=True):
        rows.append(dict(zip(headers, r)))
    return headers, rows


