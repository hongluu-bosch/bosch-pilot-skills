def test_build_payload_writes_two_xlsx_with_per_did_two_rows(synthetic_pair):
    pytest.importorskip("xlsxwriter")
    pytest.importorskip("yaml")
    pytest.importorskip("openpyxl")

    _write_minimal_yaml(synthetic_pair["mapping"])
    _write_project(synthetic_pair["project"])
    _write_fscs_json(
        synthetic_pair["fscs_json"],
        did_product_types={"0x5001": "DPB", "0x0101": "DPB"},
    )

    result = bdp.build_payload(
        mapping_path=synthetic_pair["mapping"],
        project_path=synthetic_pair["project"],
        export_path=Path("/does/not/exist"),
        txt_22_path=synthetic_pair["txt22"],
        txt_2e_path=synthetic_pair["txt2e"],
        fscs_json_path=synthetic_pair["fscs_json"],
        out_dir=synthetic_pair["out_dir"],
        report_path=synthetic_pair["report"],
        require_anchors=False,
    )

    art_22 = result.services["22"]
    art_2e = result.services["2E"]
    assert art_22.rows_written == 4   # 2 DIDs * 2 rows each
    assert art_2e.rows_written == 2   # 1 DID  * 2 rows each
    assert art_22.xlsx_path.is_file()
    assert art_2e.xlsx_path.is_file()
    assert art_22.did_hexes == ["0x5001", "0x0101"]

    headers, rows = _read_workbook(art_22.xlsx_path)
    assert "Object Heading" in headers and "Object Text" in headers
    fs_row = rows[0]
    cs_row = rows[1]
    assert fs_row["Object Heading"] == "Identifier $5001h - Vehicle mode"
    assert (cs_row["Object Heading"] is None) or (cs_row["Object Heading"] == "")
    assert (fs_row["Object Text"] is None) or (fs_row["Object Text"] == "")
    assert "body for 5001" in cs_row["Object Text"]
    assert fs_row["RB_Product"] == "DPB"
    assert cs_row["RB_Product"] == "DPB"


