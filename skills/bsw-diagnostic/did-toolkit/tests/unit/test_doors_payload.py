# --------------------------------------------------------------------- #
# v1.17.0 state machine -- INSERT / UPDATE / NOOP / STALE coverage      #
# --------------------------------------------------------------------- #
#
# These four scenarios pin the workbook-side semantics of the new
# state machine: empty state -> all INSERT, fully-stale state ->
# all UPDATE, mixed -> only changed rows land, and all-NOOP ->
# empty workbook (still on disk so the orchestrator's path
# reporting stays consistent). Together with
# ``test_doors_diff.py`` they cover both ends of the plan
# protocol, so a regression in either layer surfaces fast.

from fscs.doors.doors_state import (  # noqa: E402  (test-section local)
    DIDState,
    ModuleState,
    ServiceLanding,
    State,
    now_utc_iso,
)


_MODULE_UUID = "demo-module"  # matches doors.document_uuid in _write_minimal_yaml


def _write_state_machine_pair(synthetic_pair: dict) -> None:
    """Common fixture wiring used by every state-machine scenario:
    minimal yaml + project + fscs.json with both DIDs tagged DPB.

    Kept tiny and explicit so each scenario's assertion block reads
    independently of the others (no shared setup hidden behind a
    fixture wrapper)."""
    _write_minimal_yaml(synthetic_pair["mapping"])
    _write_project(synthetic_pair["project"])
    _write_fscs_json(
        synthetic_pair["fscs_json"],
        did_product_types={"0x5001": "DPB", "0x0101": "DPB"},
    )


def _build_with_state(
    synthetic_pair: dict,
    *,
    state: State | None,
    module_uuid: str | None,
):
    """Tiny wrapper around ``bdp.build_payload`` so each scenario only
    spells out the state plumbing it cares about. Skips
    ``require_anchors`` because the synthetic pair has no DOORS
    export."""
    return bdp.build_payload(
        mapping_path=synthetic_pair["mapping"],
        project_path=synthetic_pair["project"],
        export_path=Path("/does/not/exist"),
        txt_22_path=synthetic_pair["txt22"],
        txt_2e_path=synthetic_pair["txt2e"],
        fscs_json_path=synthetic_pair["fscs_json"],
        out_dir=synthetic_pair["out_dir"],
        report_path=synthetic_pair["report"],
        require_anchors=False,
        state=state,
        module_uuid=module_uuid,
    )


def _seed_state_for(
    *,
    pair_hashes: dict[tuple[str, str], str],
    module_uuid: str,
    fs_abs_template: str = "FS-{hex}-{svc}",
    cs_abs_template: str = "CS-{hex}-{svc}",
    overwrite_hash: dict[tuple[str, str], str] | None = None,
) -> State:
    """Build a synthetic State that records every (service, did_hex)
    in ``pair_hashes`` for ``module_uuid``.

    ``overwrite_hash`` lets a caller intentionally drift recorded
    hashes (UPDATE setup); pairs absent from it inherit the live
    hash so the diff classifies them as NOOP.
    """
    state = State()
    module = state.for_module(module_uuid)
    module.last_uploaded_at = now_utc_iso()
    overwrite_hash = overwrite_hash or {}
    for (service, did_hex), live_hash in pair_hashes.items():
        recorded_hash = overwrite_hash.get((service, did_hex), live_hash)
        landing = ServiceLanding(
            fs_abs=fs_abs_template.format(hex=did_hex, svc=service),
            cs_abs=cs_abs_template.format(hex=did_hex, svc=service),
            content_hash=recorded_hash,
            last_uploaded_at=now_utc_iso(),
        )
        module.remember(did_hex, service, landing)
    return state


def test_state_machine_pure_insert_writes_all_rows_destination_only(synthetic_pair):
    """First-ever push (empty state, fresh module): every effective
    DID×service must classify as INSERT, all FS+CS rows must land
    in the workbook, ``Destination Object`` carries the anchor (or
    the dry-run placeholder), and ``Absolute Number`` is blank.

    NB: ``RowCtx.mode`` is "insert" by default; this test pins
    that the cell-level mutations downstream actually do honour it.
    """
    pytest.importorskip("xlsxwriter")
    pytest.importorskip("yaml")
    pytest.importorskip("openpyxl")

    _write_state_machine_pair(synthetic_pair)
    state = State()  # empty -- no prior knowledge of any module

    result = _build_with_state(synthetic_pair, state=state, module_uuid=_MODULE_UUID)

    assert result.action_plan is not None
    summary = result.action_plan.summary()
    assert summary["INSERT"] == 3   # 22 has 2 DIDs, 2E has 1 DID
    assert summary["UPDATE"] == 0
    assert summary["NOOP"] == 0
    assert summary["STALE"] == 0

    art_22 = result.services["22"]
    art_2e = result.services["2E"]
    assert art_22.rows_written == 4   # 2 DIDs * 2 rows
    assert art_2e.rows_written == 2   # 1 DID  * 2 rows

    _, rows_22 = _read_workbook(art_22.xlsx_path)
    for row in rows_22:
        # Anchor placeholder lands as "" in dry-run mode -> Destination
        # Object is allowed to be blank, but the column must EXIST and
        # the Absolute Number column must be blank everywhere (INSERT).
        assert (row["Absolute Number"] is None) or (row["Absolute Number"] == "")


def test_state_machine_pure_update_writes_all_rows_with_absolute_number(synthetic_pair):
    """Every DID×service is recorded with a STALE (drifted) hash:
    the diff must classify all of them as UPDATE, the workbook
    keeps every FS+CS row, but now ``Absolute Number`` carries
    the recorded landings and ``Destination Object`` is blank
    so DOORS overwrites in place rather than re-appending."""
    pytest.importorskip("xlsxwriter")
    pytest.importorskip("yaml")
    pytest.importorskip("openpyxl")

    _write_state_machine_pair(synthetic_pair)

    # First-pass build with no state to harvest the live content
    # hashes -- we then deliberately corrupt them in the seeded
    # state so the second pass classifies everything as UPDATE.
    probe = _build_with_state(synthetic_pair, state=None, module_uuid=None)
    live_hashes = dict(probe.did_pair_hashes)
    assert live_hashes, "probe must have produced at least one pair hash"

    poisoned = "sha256:" + ("0" * 64)
    state = _seed_state_for(
        pair_hashes=live_hashes,
        module_uuid=_MODULE_UUID,
        overwrite_hash={k: poisoned for k in live_hashes},
    )

    result = _build_with_state(synthetic_pair, state=state, module_uuid=_MODULE_UUID)

    summary = result.action_plan.summary()
    assert summary["UPDATE"] == 3
    assert summary["INSERT"] == 0
    assert summary["NOOP"] == 0

    art_22 = result.services["22"]
    assert art_22.rows_written == 4   # UPDATE still emits FS+CS

    _, rows_22 = _read_workbook(art_22.xlsx_path)
    for row in rows_22:
        # UPDATE inverts the cell pair: Destination Object blank,
        # Absolute Number filled with the recorded landing.
        assert (row["Destination Object"] is None) or (row["Destination Object"] == "")
        assert row["Absolute Number"] not in (None, "")
        # Recorded values come from _seed_state_for's templates so
        # we can sanity-check the wiring end-to-end.
        assert row["Absolute Number"].startswith(("FS-0x", "CS-0x"))


def test_state_machine_mixed_insert_update_noop_skips_only_noop_rows(synthetic_pair):
    """The interesting middle case: one DID per bucket. The NOOP
    DID must not appear in the workbook at all (cheapest possible
    push), while INSERT and UPDATE still land FS+CS rows with
    their correct cell semantics."""
    pytest.importorskip("xlsxwriter")
    pytest.importorskip("yaml")
    pytest.importorskip("openpyxl")

    _write_state_machine_pair(synthetic_pair)

    probe = _build_with_state(synthetic_pair, state=None, module_uuid=None)
    live_hashes = dict(probe.did_pair_hashes)

    # 22 has two DIDs (5001, 0101), 2E has one (0101). Pin:
    #   ("22", "0x5001") -> NOOP  (recorded with matching hash)
    #   ("22", "0x0101") -> UPDATE (recorded with poisoned hash)
    #   ("2E", "0x0101") -> INSERT (NOT recorded at all)
    poisoned = "sha256:" + ("a" * 64)
    state = State()
    module = state.for_module(_MODULE_UUID)
    module.last_uploaded_at = now_utc_iso()
    module.remember(
        "0x5001", "22",
        ServiceLanding(
            fs_abs="ABS-NOOP-FS",
            cs_abs="ABS-NOOP-CS",
            content_hash=live_hashes[("22", "0x5001")],
            last_uploaded_at=now_utc_iso(),
        ),
    )
    module.remember(
        "0x0101", "22",
        ServiceLanding(
            fs_abs="ABS-UPDATE-FS",
            cs_abs="ABS-UPDATE-CS",
            content_hash=poisoned,
            last_uploaded_at=now_utc_iso(),
        ),
    )

    result = _build_with_state(synthetic_pair, state=state, module_uuid=_MODULE_UUID)

    summary = result.action_plan.summary()
    assert summary["NOOP"] == 1
    assert summary["UPDATE"] == 1
    assert summary["INSERT"] == 1
    assert summary["STALE"] == 0

    art_22 = result.services["22"]
    art_2e = result.services["2E"]
    # 22 sheet: NOOP (5001) skipped + UPDATE (0101) FS+CS = 2 rows
    assert art_22.rows_written == 2
    assert art_22.did_hexes == ["0x0101"]   # NOOP'd hex must NOT be listed
    # 2E sheet: INSERT (0101) FS+CS = 2 rows
    assert art_2e.rows_written == 2
    assert art_2e.did_hexes == ["0x0101"]

    _, rows_22 = _read_workbook(art_22.xlsx_path)
    # Every surviving 22 row is the UPDATE -> Absolute Number filled,
    # Destination Object blank.
    for row in rows_22:
        assert row["Absolute Number"] in ("ABS-UPDATE-FS", "ABS-UPDATE-CS")
        assert (row["Destination Object"] is None) or (row["Destination Object"] == "")

    _, rows_2e = _read_workbook(art_2e.xlsx_path)
    # The 2E row pair is an INSERT -> Absolute Number blank.
    for row in rows_2e:
        assert (row["Absolute Number"] is None) or (row["Absolute Number"] == "")


