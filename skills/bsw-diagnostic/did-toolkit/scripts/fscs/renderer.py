"""Render an :class:`FSCSDocument` to JSON bytes or plaintext FSCS files.

Design notes
------------

FSCS ``.txt`` output has tab-aligned columns and a byte-offset state
machine that walks ``sub_fields`` to produce the Positive Response
Message table. Previous phase-6 refactoring consciously left FSCS on
f-strings (instead of migrating to Jinja2) because the layout is more
readable as imperative ``lines.append(...)`` than as templates riddled
with whitespace-control tags.

This module preserves that decision: pure Python rendering functions,
every helper stateless and unit-testable. The JSON side is a thin
wrapper around ``pydantic.BaseModel.model_dump_json``.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation
from typing import Iterable, List

from .schema import (
    DIDFscsEntry,
    FSCSDocument,
    FSCSSecurityLevel,
    FSCSServiceAccess,
    FSCSSubField,
    FSCSValueRangeComposite,
    FSCSValueRangeEnum,
    FSCSValueRangeNone,
    FSCSValueRangeNumeric,
)


SEPARATOR = "=" * 80
_DATA_RECORD_LABEL_PADDING = 4
_DATA_RECORD_LABEL_MIN_WIDTH = 16
_VALUE_RANGE_WRAP_WIDTH = 80


# Leading banner written at the top of every ``FSCS_*.txt`` file. It
# exists to remind human reviewers that the plaintext view is a
# *derived* artifact of ``outputs/fscs/fscs.json`` -- hand-editing the
# ``.txt`` will be silently overwritten on the next pipeline run.
#
# The banner is intentionally self-contained (no dynamic timestamp, no
# path interpolation) so golden-file diffs stay stable and byte-wise
# reproducible across machines.
TXT_HEADER = (
    "# "
    + ("=" * 78)
    + "\n"
    "# Generated from outputs/fscs/fscs.json -- do not edit this file by hand.\n"
    "#\n"
    "# Workflow:\n"
    "#   1. Edit outputs/fscs/fscs_edit.xlsx.\n"
    "#   2. Run `python scripts/pipeline.py --phase xlsx-import`.\n"
    "#   3. Re-run Phase 2 / Phase 3 to refresh downstream artefacts.\n"
    "# "
    + ("=" * 78)
    + "\n"
    "\n"
)


# ---------------------------------------------------------------------------
# JSON side
# ---------------------------------------------------------------------------


def render_fscs_json(doc: FSCSDocument) -> str:
    """Serialise an ``FSCSDocument`` to a pretty-printed JSON string.

    The output is deterministic (key order follows the pydantic field
    declaration order; indent is 2; trailing newline added) so golden
    file diffs stay stable across runs.
    """
    # pydantic preserves declared field order; mode='json' makes sure
    # tagged-union discriminators + enums come out as strings.
    data = doc.model_dump(mode="json")
    rendered = json.dumps(data, indent=2, ensure_ascii=False)
    if not rendered.endswith("\n"):
        rendered += "\n"
    return rendered


