def _guess_signal_local_name(signal_name: str) -> str:
    tokens = re.split(r"[^A-Za-z0-9]+", signal_name)
    suffix = "_".join(token for token in tokens if token)
    return f"l_{suffix}" if suffix else "l_Value"


def _can_build_single_byte_bit_pack(did: SnapshotDIDInfo, items: List[str]) -> bool:
    if did.size_bytes != 1:
        return False
    if len(items) < 2:
        return False
    if any(item.endswith(")") or "." in item for item in items):
        return False
    notes = (did.impl_notes or "").lower()
    return all(f"bit{i}=" in notes for i in range(min(len(items), 6)))


def _build_single_byte_bit_pack_content(did: SnapshotDIDInfo, record_numbers: List[str], items: List[str]) -> str | None:
    file_name = build_snapshot_c_filename(did)
    short_name = did.read_fnc.replace("_ReadData", "")
    local_names = [_guess_signal_local_name(item) for item in items]
    expr_parts = []
    for idx, local_name in enumerate(local_names):
        if idx == 0:
            expr_parts.append(f"({local_name} != 0u ? 0x01u : 0x00u)")
        else:
            expr_parts.append(f"(({local_name} != 0u ? 0x01u : 0x00u) << {idx})")
    packed_expr = " | ".join(expr_parts) if expr_parts else "0x00u"

    lines = [
        "/**",
        " * @ingroup 'RBAPLCust'",
        " *",
        f" * {file_name}",
        " * Generated by 19service-toolkit -- do not edit by hand.",
        " *",
        " * \\copyright",
        " * Robert Bosch GmbH reserves all rights even in the event of industrial property rights.",
        " * We reserve all rights of disposal such as copying and passing on to third parties.",
        " */",
        "",
        "/* USED_INTERFACES: */",
        '#include "Dcm.h"',
        '#include "Dcm_Lcfg_DspUds.h"',
        "",
        "/* REALIZED_INTERFACES: */",
        '#include "RBAPLCust_Config.h"',
        '#include "RBMESG_Explicit.h"',
        '#include "RBAPLCUST_Global.h"',
        "",
        "",
        f"/* Snapshot DID  : {did.did_hex}",
        f" * ShortName    : {short_name}",
        f" * Size         : {did.size_bytes} bytes",
        f" * Product Type : {did.product_type}",
        f" * Record Nos   : {', '.join(record_numbers)}",
        " */",
        "",
        f"Std_ReturnType {did.read_fnc}(uint8* Data)",
        "{",
    ]

    for local_name in local_names:
        lines.append(f"    UBYTE {local_name};")
    lines.append("")

    for local_name, signal_name in zip(local_names, items):
        lines.append(f"    RcvMESG({local_name}, {signal_name});")
    lines.append("")
    lines.append(f"    Data[0] = (uint8)({packed_expr});")
    lines.extend([
        "",
        "    return E_OK;",
        "}",
        "",
    ])
    return "\n".join(lines)


