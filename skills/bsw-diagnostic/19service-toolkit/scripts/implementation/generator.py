        " * We reserve all rights of disposal such as copying and passing on to third parties.",
        " */",
        "",
        "/* USED_INTERFACES: */",
        '#include "Dcm.h"',
        '#include "Dcm_Lcfg_DspUds.h"',
        "",
        "/* REALIZED_INTERFACES: */",
        '#include "RBAPLCust_Config.h"',
        '#include "RBMESG_Explicit.h"',
        '#include "RBAPLCUST_Global.h"',
