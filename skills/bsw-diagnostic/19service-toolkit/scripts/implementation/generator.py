def try_build_real_snapshot_c_content(did: SnapshotDIDInfo, record_numbers: List[str]) -> str | None:
    """Return a concrete implementation when the input is unambiguous.

    Phase 3 intentionally stays conservative.  At the moment only a single
    getter-call source is implemented automatically.  Everything else keeps the
    TODO stub until the user input and signal analysis are extended further.
    """
    items = [item.strip() for item in did.impl_signal_list.split(";") if item.strip()]
    if len(items) == 1 and items[0].endswith(")"):
        return _build_getter_impl_content(did, record_numbers, items[0])

    if _can_build_scalar_copy_sequence(items):
        return _build_scalar_copy_sequence_content(did, record_numbers, items)

    if _can_build_single_byte_bit_pack(did, items):
        return _build_single_byte_bit_pack_content(did, record_numbers, items)

    if _can_build_struct_be_with_qualifier_and_scaling(did, items):
        return _build_struct_be_with_qualifier_and_scaling_content(did, record_numbers, items)

    if _can_build_struct_be_with_qualifier(did, items):
        return _build_struct_be_with_qualifier_content(did, record_numbers, items)

    notes = (did.impl_notes or "").lower()
    if did.size_bytes == 1 and len(items) == 2 and all(not item.endswith(")") and "." not in item for item in items):
        if "low nibble" in notes and "high nibble" in notes:
            return _build_simple_nibble_pack_content(did, record_numbers, items)

    if _can_build_simple_nibble_pack(did, items):
        return _build_simple_nibble_pack_content(did, record_numbers, items)

    return None


def _clean_name(name: str) -> str:
    for pattern in _SUFFIX_NOISE:
        name = re.sub(pattern, "", name, flags=re.IGNORECASE)
    words = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(w[:1].upper() + w[1:] for w in words if w)


