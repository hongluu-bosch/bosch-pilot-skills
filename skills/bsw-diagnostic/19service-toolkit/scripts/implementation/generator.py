def _guess_local_name(getter_call: str) -> str:
    base = getter_call.split("(", 1)[0].split("::")[-1]
    words = re.split(r"[^A-Za-z0-9]+", base)
    suffix = "".join(w[:1].upper() + w[1:] for w in words if w)
    return f"l_{suffix}" if suffix else "l_Value"


def _guess_getter_transform(did: SnapshotDIDInfo, local_name: str) -> str:
    # First supported template: single-byte battery/power-supply style scaling.
    lower = did.did_name_en.lower()
    if did.size_bytes == 1 and any(k in lower for k in ("battery", "voltage", "power supply")):
        return f"(uint8)(((({local_name} * 100u) / 256u)) >> 3u)"
    return f"(uint8)({local_name})"


def _can_build_scalar_copy_sequence(items: List[str]) -> bool:
    if not items:
        return False
    for item in items:
        if item.endswith(")"):
            return False
        if "." in item:
            return False
    return True


