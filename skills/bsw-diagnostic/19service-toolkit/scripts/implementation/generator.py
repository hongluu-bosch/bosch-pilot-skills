def _guess_pattern(name: str) -> str:
    lower = name.lower()
    if any(k in lower for k in ("wheel speed", "vehicle speed", "speed")):
        return "RAM / internal interface (MESG struct, big-endian 16-bit values)"
    if any(k in lower for k in ("battery", "voltage", "power supply")):
        return "RAM / internal getter (direct function call + scaling)"
    if any(k in lower for k in ("avh", "apb", "epb", "autohold", "actuator")):
        return "RAM / internal interface (RBMESG, PbcOut or NMSG signals)"
    if any(k in lower for k in ("time", "year", "month", "day", "hour", "min", "sec")):
        return "RAM / internal interface (scalar NMSG time signals via RcvMESG)"
    if any(k in lower for k in ("sensor", "yaw", "acceleration", "pressure", "steering")):
        return "RAM / internal interface (MESG struct with qualifier check)"
    if any(k in lower for k in ("status", "state", "flag")):
        return "RAM / internal interface (bit-packed status byte(s))"
    return "RAM / internal interface (pattern undetermined; inspect project signals)"


def _render_sub_fields(did: SnapshotDIDInfo) -> List[str]:
    lines: List[str] = []
    for sf in did.sub_fields:
        if not any(sf.get(k) for k in ("name_en", "byte", "resolution", "range_min", "range_max", "unit")):
            continue
        if not sf.get("name_en") and not sf.get("byte"):
            continue
        name = sf.get("name_en", "") or "<unnamed field>"
        rng = f"[{sf.get('range_min', '')} ~ {sf.get('range_max', '')} {sf.get('unit', '').strip()}]".strip()
        res = sf.get("resolution", "")
        byte = sf.get("byte", "")
        prefix = f"Byte {byte} : " if byte else ""
        payload = f"{name} {rng}, res={res}".rstrip().rstrip(",")
        lines.append(f"{prefix}{payload}".rstrip())
    if not lines:
        lines.append("No structured sub-field data available.")
    return lines


